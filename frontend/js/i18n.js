window.NagrikI18n = {
  current: localStorage.getItem('nagriksnap_lang') || 'en',
  t(key) {
    const lang = this.current;
    return (TRANSLATIONS[lang] && TRANSLATIONS[lang][key]) || (TRANSLATIONS.en && TRANSLATIONS.en[key]) || key;
  },
  setLang(code) {
    if (!TRANSLATIONS[code]) return;
    this.current = code;
    localStorage.setItem('nagriksnap_lang', code);
    document.documentElement.lang = code === 'raj' ? 'hi' : code;
    this.apply();
  },
  apply() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      // Skip if a parent also has data-i18n (avoid double translate)
      if (el.parentElement && el.parentElement.closest('[data-i18n]') && el.parentElement.closest('[data-i18n]') !== el) {
        // only skip if parent is an ancestor with data-i18n
      }
      const key = el.getAttribute('data-i18n');
      const val = this.t(key);
      if (!val) return;

      // Count element children (icons etc.)
      const elementChildren = Array.from(el.children);
      const hasOnlyIcons = elementChildren.length > 0 && elementChildren.every(c =>
        c.tagName === 'I' || c.tagName === 'SVG' || c.classList.contains('logo-icon') || c.tagName === 'IMG'
      );

      if (elementChildren.length === 0) {
        // Pure text element
        el.textContent = val;
      } else if (hasOnlyIcons) {
        // Keep icons, set rest as single text node
        elementChildren.forEach(c => el.appendChild(c)); // keep order
        // Remove all text nodes first
        Array.from(el.childNodes).forEach(n => {
          if (n.nodeType === 3) n.remove();
        });
        el.appendChild(document.createTextNode(' ' + val));
      } else {
        // Complex: only update direct text nodes that have content, do NOT append
        let updated = false;
        Array.from(el.childNodes).forEach(n => {
          if (n.nodeType === 3 && n.textContent.trim()) {
            n.textContent = val;
            updated = true;
          }
        });
        if (!updated && !el.querySelector('[data-i18n]')) {
          el.textContent = val;
        }
      }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      el.placeholder = this.t(el.getAttribute('data-i18n-placeholder'));
    });

    // Remove nested data-i18n inside another data-i18n to prevent double text
    document.querySelectorAll('[data-i18n] [data-i18n]').forEach(inner => {
      inner.removeAttribute('data-i18n');
    });

    const sel = document.getElementById('langSelect');
    if (sel) sel.value = this.current;
  },

  initSwitcher() {
    if (document.getElementById('langSelect')) return;
    const nav = document.querySelector('.nav-links');
    if (!nav) return;
    const wrap = document.createElement('div');
    wrap.className = 'lang-switcher';
    wrap.innerHTML = '<select id="langSelect" title="Language" aria-label="Select language">' +
      Object.keys(LANG_META).map(c => '<option value="'+c+'">'+LANG_META[c].native+'</option>').join('') +
      '</select>';
    nav.appendChild(wrap);
    const sel = document.getElementById('langSelect');
    sel.value = this.current;
    sel.addEventListener('change', e => this.setLang(e.target.value));
  }
};

document.addEventListener('DOMContentLoaded', () => {
  NagrikI18n.initSwitcher();
  NagrikI18n.apply();
});
